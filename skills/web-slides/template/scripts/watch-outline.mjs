#!/usr/bin/env node
/**
 * Watch content/deck.outline.md and regenerate src/slides/generated/from-outline.tsx.
 * Usage:
 *   node scripts/watch-outline.mjs           # once
 *   node scripts/watch-outline.mjs --watch   # rebuild on change
 * Called by `npm run live` together with Vite.
 */
import { mkdirSync, readFileSync, watch, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outlinePath = join(root, "content", "deck.outline.md");
const outDir = join(root, "src", "slides", "generated");
const outFile = join(outDir, "from-outline.tsx");
const watching = process.argv.includes("--watch");

function esc(s) {
  return s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$/g, "\\$");
}

function parseOutline(md) {
  const lines = md.split(/\r?\n/);
  let deckTitle = "Deck";
  let theme = "midnight";
  const slides = [];
  let cur = null;
  for (const raw of lines) {
    const line = raw.trimEnd();
    if (/^#\s+/.test(line) && !/^##\s+/.test(line)) {
      deckTitle = line.replace(/^#\s+/, "").trim();
      continue;
    }
    const themeM = line.match(/^Theme:\s*(\S+)/i);
    if (themeM) { theme = themeM[1]; continue; }
    if (line.startsWith("<!--") || line.startsWith("-->") || !line.trim()) continue;
    const hm = line.match(/^##\s+([a-z0-9-]+)\s*\|\s*(.+)$/i);
    if (hm) {
      cur = { id: hm[1].toLowerCase(), kicker: hm[2].trim(), title: "", bullets: [] };
      slides.push(cur);
      continue;
    }
    const tm = line.match(/^Takeaway:\s*(.+)$/i);
    if (tm && cur) { cur.title = tm[1].trim(); continue; }
    const bm = line.match(/^-\s+(.+)$/);
    if (bm && cur) { cur.bullets.push(bm[1].trim()); continue; }
  }
  return { deckTitle, theme, slides: slides.filter((s) => s.title) };
}

function render({ deckTitle, theme, slides }) {
  const blocks = slides.map((s, i) => {
    const id = s.id.replace(/[^a-z0-9-]/g, "") || `slide-${i + 1}`;
    const bullets = s.bullets.slice(0, 5);
    const list = bullets.length
      ? `<ul className="muted" style={{ fontSize: 28, lineHeight: 1.45, margin: 0, paddingLeft: "1.1em" }}>
${bullets.map((b) => `          <li>${esc(b)}</li>`).join("\n")}
        </ul>`
      : `<p className="muted">Refine this stub in a dedicated slide file for layout and diagrams.</p>`;
    return `const s${i} = defineSlide({
  id: "outline-${id}",
  notes: "Generated from content/deck.outline.md — refine into a typed slide file for production beauty.",
  Component: () => (
    <SlideFrame kind="${id === "title" ? "title" : id === "closing" ? "closing" : "content"}" kicker="${esc(s.kicker)}"
      title="${esc(s.title)}"${id === "title" ? ' background="aurora" center' : ""}>
      ${list}
    </SlideFrame>
  ),
});`;
  }).join("\n\n");

  const exports = slides.map((_, i) => `s${i}`).join(", ");
  return `/* AUTO-GENERATED by scripts/watch-outline.mjs from content/deck.outline.md — do not edit by hand. */
import { SlideFrame } from "../../deck/components";
import { defineSlide, type SlideDef } from "../../deck/types";

${blocks}

/** Stub slides from the live outline. Import into index.ts to preview, then replace with polished files. */
export const outlineSlides: SlideDef[] = [${exports}];
export const outlineMeta = ${JSON.stringify({ deckTitle, theme, count: slides.length }, null, 2)} as const;
`;
}

function build() {
  if (!existsSync(outlinePath)) {
    console.error(`missing ${outlinePath}`);
    process.exit(1);
  }
  mkdirSync(outDir, { recursive: true });
  const parsed = parseOutline(readFileSync(outlinePath, "utf8"));
  writeFileSync(outFile, render(parsed));
  // marker for Vite / git
  writeFileSync(join(outDir, ".gitkeep"), "");
  console.log(`outline → ${outFile} (${parsed.slides.length} slides, theme=${parsed.theme})`);
}

build();
if (watching) {
  console.log(`watching ${outlinePath}`);
  let t = null;
  watch(outlinePath, () => {
    clearTimeout(t);
    t = setTimeout(() => {
      try { build(); } catch (e) { console.error(e); }
    }, 80);
  });
}
